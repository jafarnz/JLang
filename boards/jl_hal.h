/*
 * jl_hal.h - the functions a board provides to JLang native code.
 *
 * `jlang build app.jlang` produces RISC-V assembly that calls these. To
 * support a new RISC-V board, implement them in C with the board's SDK,
 * then call jl_main() once and jl_on_<event>() when an event happens.
 */
#ifndef JL_HAL_H
#define JL_HAL_H

void jl_hal_putc(int c);               /* print one character */
void jl_hal_halt(int code);            /* a runtime error happened: stop */
void jl_hal_pin_mode(int pin, int mode); /* 0 = input, 1 = output, 2 = input with pull-up */
void jl_hal_pin_write(int pin, int level);
int jl_hal_pin_read(int pin);
void jl_hal_delay(int ms);
int jl_hal_millis(void);

/* Only needed by programs that use the LED panel built-ins. Pixels outside
   the panel should be ignored. */
void jl_hal_led_set(int x, int y, int rgb); /* rgb is 0xRRGGBB */
void jl_hal_led_show(void);
void jl_hal_led_clear(void);
int jl_hal_led_width(void);
int jl_hal_led_height(void);

/* Generated by jlang build. */
void jl_main(void);

#endif
